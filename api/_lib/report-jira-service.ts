export interface JiraReportResult {
  key?: string;
  url?: string;
  error?: string;
}

function buildReportAdf(type: ReportType, now: string) {
  const label =
    type === "all" ? "Daily + Weekly + Monthly" : type.charAt(0).toUpperCase() + type.slice(1);

  const row = (key: string, val: string) => ({
    type: "listItem",
    content: [
      {
        type: "paragraph",
        content: [
          { type: "text", text: `${key}: `, marks: [{ type: "strong" }] },
          { type: "text", text: val },
        ],
      },
    ],
  });

  return {
    type: "doc",
    version: 1,
    content: [
      {
        type: "heading",
        attrs: { level: 2 },
        content: [{ type: "text", text: `ProfitMachines ${label} Report Automation` }],
      },
      {
        type: "paragraph",
        content: [
          {
            type: "text",
            text: "This task was auto-generated by the Vercel /api/process-report endpoint.",
          },
        ],
      },
      {
        type: "heading",
        attrs: { level: 3 },
        content: [{ type: "text", text: "Report Details" }],
      },
      {
        type: "bulletList",
        content: [
          row("Report Type", label),
          row("Triggered At (UTC)", now),
          row("Google Sheets Dashboard", SPREADSHEET_URL),
          row("Recipients", TEAM_EMAIL),
          row("Source", "Vercel Cron / API -> Apps Script -> Gmail"),
        ],
      },
      {
        type: "heading",
        attrs: { level: 3 },
        content: [{ type: "text", text: "Pipeline Checklist" }],
      },
      {
        type: "bulletList",
        content: [
          row("1. Google Sheets summaries updated", "Automated"),
          row("2. HTML digest email dispatched", "Automated (Gmail via Apps Script)"),
          row("3. Jira task created", "This task"),
          row("4. Notification status", "Recorded"),
        ],
      },
    ],
  };
}

/**
 * Searches for an existing report task today using Jira Cloud's /search/jql API.
 * Updates the existing task if found (idempotent), otherwise creates a new Task.
 */
export async function createOrUpdateJiraReportTask(
  type: ReportType,
  now: string
): Promise<JiraReportResult> {
  if (!JIRA_API_TOKEN) {
    return { error: "JIRA_API_TOKEN not configured" };
  }

  const label = type === "all" ? "Full Suite" : type.charAt(0).toUpperCase() + type.slice(1);
  const dateStr = now.slice(0, 10);
  const summary = `[ProfitMachines Report] ${label} Executive Digest - ${dateStr}`;
  const desc = buildReportAdf(type, now);
  const auth = "Basic " + Buffer.from(`${JIRA_EMAIL}:${JIRA_API_TOKEN}`).toString("base64");
  const apiBase = `https://${JIRA_HOST}/rest/api/3`;

  // 1. Search for existing task created today using latest /search/jql API (Idempotency)
  try {
    const jql = `project = ${JIRA_PROJECT_KEY} AND summary ~ "${label}" AND created >= -1d ORDER BY created DESC`;
    const searchRes = await fetch(
      `${apiBase}/search/jql?jql=${encodeURIComponent(jql)}&fields=key,summary&maxResults=1`,
      {
        headers: { Authorization: auth, Accept: "application/json" },
      }
    );

    if (searchRes.ok) {
      const data = await searchRes.json();
      if (data?.issues?.length > 0 && data.issues[0]?.key) {
        const existingKey: string = data.issues[0].key;
        await fetch(`${apiBase}/issue/${existingKey}`, {
          method: "PUT",
          headers: {
            Authorization: auth,
            Accept: "application/json",
            "Content-Type": "application/json",
          },
          body: JSON.stringify({ fields: { description: desc } }),
        });
        return { key: existingKey, url: `https://${JIRA_HOST}/browse/${existingKey}` };
      }
    }
  } catch {
    /* fall through to create */
  }

  // 2. Create new Jira Task
  try {
    const payload = {
      fields: {
        project: { key: JIRA_PROJECT_KEY },
        summary,
        description: desc,
        issuetype: { name: "Task" },
        labels: ["profitmachines", "automated-report", `${type}-report`, "report-automation"],
      },
    };

    const createRes = await fetch(`${apiBase}/issue`, {
      method: "POST",
      headers: {
        Authorization: auth,
        Accept: "application/json",
        "Content-Type": "application/json",
      },
      body: JSON.stringify(payload),
    });

    if (createRes.ok) {
      const createData = await createRes.json();
      return { key: createData.key, url: `https://${JIRA_HOST}/browse/${createData.key}` };
    }

    const errText = await createRes.text();
    return { error: `Jira create failed (${createRes.status}): ${errText.slice(0, 300)}` };
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : String(err);
    return { error: `Jira error: ${msg}` };
  }
}
